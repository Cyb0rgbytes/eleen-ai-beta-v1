#!/usr/bin/env node
/**
 * Generate web/src/ui/icons.data.ts from Phosphor's regular-weight SVGs.
 *
 * Only the glyphs listed here ship, as path data. web/src/ui/icons.ts turns
 * them into <svg> elements with createElementNS, so no icon ever goes
 * through an HTML parser and the bundle carries exactly what the page uses.
 *
 * `mirror` marks glyphs that imply a direction; DESIGN.md section 6 says
 * those flip in RTL and the rest do not.
 *
 *   node scripts/gen-icons.mjs           write the file
 *   node scripts/gen-icons.mjs --check   fail if it is out of date
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const ICONS = {
	"arrow-up": { mirror: false }, // send
	stop: { mirror: false }, // stop generating
	microphone: { mirror: false },
	"sign-in": { mirror: true },
	"sign-out": { mirror: true },
	"check-circle": { mirror: false },
	"circle-notch": { mirror: false }, // spinner glyph for a busy button
	"thumbs-up": { mirror: false },
	"thumbs-down": { mirror: false },
	sparkle: { mirror: false }, // enhance prompt
	copy: { mirror: false },
	check: { mirror: false },
	"arrow-down": { mirror: false }, // jump to latest
	"arrow-clockwise": { mirror: false }, // regenerate
	"caret-down": { mirror: false }, // picker trigger
	"lock-simple": { mirror: false }, // locked model
	x: { mirror: false }, // dismiss
	"warning-circle": { mirror: false }, // error state
	key: { mirror: false }, // keys form
};

const SOURCE = "node_modules/@phosphor-icons/core/assets/regular";
const OUT = "web/src/ui/icons.data.ts";

const entries = Object.entries(ICONS).map(([name, { mirror }]) => {
	const file = join(SOURCE, `${name}.svg`);
	if (!existsSync(file)) throw new Error(`Phosphor has no regular glyph named ${name}`);
	const svg = readFileSync(file, "utf8");
	const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1];
	if (viewBox !== "0 0 256 256") throw new Error(`${name}: unexpected viewBox ${viewBox}`);
	const others = [...svg.matchAll(/<(\w+)/g)].map((m) => m[1]).filter((t) => t !== "svg" && t !== "path");
	if (others.length) throw new Error(`${name}: uses <${others[0]}>, only <path> is supported`);
	const paths = [...svg.matchAll(/<path\b[^>]*\bd="([^"]+)"/g)].map((m) => m[1]);
	if (!paths.length) throw new Error(`${name}: no paths`);
	return [name, { paths, mirror }];
});

const body =
	"// Generated by scripts/gen-icons.mjs from @phosphor-icons/core (MIT). Do not edit.\n" +
	"// Regular weight, viewBox 0 0 256 256.\n\n" +
	"export const ICON_DATA = {\n" +
	entries
		.map(
			([name, { paths, mirror }]) =>
				`\t${JSON.stringify(name)}: { mirror: ${mirror}, paths: [${paths.map((p) => JSON.stringify(p)).join(", ")}] },`,
		)
		.join("\n") +
	"\n} as const;\n\n" +
	"export type IconName = keyof typeof ICON_DATA;\n";

if (process.argv.includes("--check")) {
	const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
	if (current !== body) {
		console.error(`${OUT} is out of date. Run node scripts/gen-icons.mjs.`);
		process.exit(1);
	}
	console.log(`${entries.length} icons current.`);
} else {
	writeFileSync(OUT, body);
	console.log(`Wrote ${entries.length} icons to ${OUT}.`);
}
